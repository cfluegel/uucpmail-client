// Package i18n ist die einfache Übersetzungsschicht (DE/EN).
package i18n

import (
	"os"
	"strings"
)

var lang = "en"

// Init setzt die Sprache: explizit aus der Config ("de"/"en") oder, wenn leer,
// aus der OS-Locale (LANG/LC_ALL; Fallback en).
func Init(configured string) {
	switch configured {
	case "de", "en":
		lang = configured
		return
	}
	loc := os.Getenv("LC_ALL")
	if loc == "" {
		loc = os.Getenv("LANG")
	}
	if strings.HasPrefix(strings.ToLower(loc), "de") {
		lang = "de"
	} else {
		lang = "en"
	}
}

// Lang liefert die aktive Sprache.
func Lang() string { return lang }

// T übersetzt einen Schlüssel; unbekannte Schlüssel werden selbst zurückgegeben.
func T(key string) string {
	if m, ok := tables[lang]; ok {
		if s, ok := m[key]; ok {
			return s
		}
	}
	if s, ok := tables["en"][key]; ok {
		return s
	}
	return key
}

